/// AGENTS.md (issue #204): the generated agent manual for the
/// `~/.cube-sandbox` dot-dir. ONE generator feeds three seams:
///
/// - the ensure path (resolver user-dot-dir touchpoints): write-if-missing;
/// - the `init [--force]` verb (`--force` is the ONLY overwrite seam);
/// - install.sh, which shells out to the binary's `init` after install.
///
/// Refresh policy (chosen in the issue): cube-sandbox NEVER rewrites an
/// existing AGENTS.md. A differing file earns exactly ONE stderr notice
/// per process pointing at `cube-sandbox init --force` — never a silent
/// overwrite, never notice spam. The service-grant section is derived
/// from kServiceCatalog, so the manual cannot drift from the catalog
/// without a red REG pin.
library;

import 'dart:io' as io;

import 'service_grants.dart';

/// The generated manual (lexical spelling).
const String kAgentsMdPath = '~/.cube-sandbox/AGENTS.md';

/// At most one differing-file notice per process (AC3).
bool _noticed = false;

/// Test seam: clears the per-process notice guard.
void resetAgentsMdNotice() => _noticed = false;

/// The generated manual text. Pure; every call returns identical bytes
/// for a given build (idempotency depends on it).
String generateAgentsMd() {
  final catalogLines = [
    for (final g in kServiceCatalog)
      '- `--use-${g.id}` — '
          '${g.read.isEmpty ? '' : 'ro ${g.read.join(', ')}'}'
          '${g.read.isEmpty || g.write.isEmpty ? '' : ' + '}'
          '${g.write.isEmpty ? '' : 'rw ${g.write.join(', ')}'}'
          '${g.description == null ? '' : ' — ${g.description}'}',
  ];
  return '''
# cube-sandbox agent manual

Generated by cube-sandbox. Do not hand-edit this file: a plain
`cube-sandbox init` never overwrites it, and `cube-sandbox init --force`
replaces it with the current text. Full usage: `cube-sandbox --help`;
`--version` prints the version.

## Dot-dir layout (~/.cube-sandbox)

- `bin/cube-sandbox` — the launcher binary.
- `version.txt` — installed version marker.
- `<name>.yaml` — user harness profiles (the filename stem is the id).
- `folders.yaml` — named folder-grant groups, selected with `--folders`.
- `services.yaml` — custom service grants, used with `--use-<name>`.
- `<project>/.cube-sandbox/` — per-project profiles and `cache/`.

Profile resolution order: `--file` > `<cwd>/.cube-sandbox/<name>.yaml` >
`~/.cube-sandbox/<name>.yaml` > preset. If the same stem exists in the
project dir and the user dir with DIFFERENT content, launch prints a
shadow warning and the banner `source :` line names the winner.

`<project>/.cube-sandbox/cache/` holds staged `harness-<key10>.sb` kernel
profiles, each with a `.src` provenance stamp. Any configuration change
produces a new key10, and the next launch rebuilds. `cube-sandbox clean`
deletes the cache — run it between sessions.

## Harness profiles

Create one:

    cube-sandbox new <name> --command <cmd> --agent-root <path>

`new` writes `<project>/.cube-sandbox/<name>.yaml` and refuses to
overwrite. Move the file to `~/.cube-sandbox/` to make it user-level.
The name matches ^[a-z][a-z0-9-]*\$.

Manifest format — strict parse: an unknown key at ANY level is a config
error naming the YAML path (exit 2):

    apiVersion: cube-sandbox/v1
    kind: Harness
    metadata:
      name: mytool
      description: optional one-liner
    spec:
      command: mytool          # string or argv list
      agentRoot: ~/.mytool     # rw state root
      agentRootEnv: MY_DIR     # env var overriding agentRoot
      widenToDotParent: true   # ~/.mytool/agent -> ~/.mytool
      extraRead: []            # read-only grants
      extraWrite: []           # read-write grants
      extraWritePrefix: []     # rw prefix grants (path + prefix siblings)
      network: open            # v1: open only

Validate before launch: `cube-sandbox sbpl <name>` prints the exact
kernel profile; `cube-sandbox show <name>` prints the grants banner;
`cube-sandbox probe <name>` self-checks the boundary from inside
(exit 0 = confined and working). Do not hand back a profile that fails
probe.

Launch options precede the profile: `--file <f>` (explicit manifest),
`--yaml <text|->` (inline manifest, `-` reads stdin; `--yaml` + `--file`
together is an error), `--use-*`, `--folders <group,...>`, `--wait`
(blocking parent; signal n => 128+n), `--spawn-exit` (compatibility
shape). Everything after the profile name is the harness argv, forwarded
verbatim.

## Service grants (--use-*)

${catalogLines.join('\n')}

Flags union and dedup; flag order never changes the result. Unknown
`--use-x` fails closed (exit 2) listing what exists — a typo never
degrades to "no grant". A new BUILT-IN service is a code change: append
a `ServiceGrant` to `kServiceCatalog` in `lib/src/service_grants.dart`
(REG pins the catalog; the build goes red without a GOAL revision).

### Custom service profiles (services.yaml)

Add a custom `--use-<name>` grant with NO rebuild: edit
`~/.cube-sandbox/services.yaml`. Pure data — save the file and the next
run uses it.

    # ~/.cube-sandbox/services.yaml
    apiVersion: cube-sandbox/v1
    services:
      scratch:
        description: rw scratch for data jobs
        read:                    # ro grants
          - ~/shared/notes
        write:                   # rw grants (caches, scratch dirs)
          - ~/work/scratch
        env:                     # set for the confined command
          SCRATCH_HOST: localhost

Workflow: create or edit the file, dry-run it with
`cube-sandbox show <profile> --use-scratch`, then
`cube-sandbox launch --use-scratch <profile>`. Remove a profile by
deleting its entry. The schema is strict — unknown key, bad name, unsafe
path, or non-scalar env value is an exit-2 error naming the file AND the
line (`services.yaml:<line>: ...`). Names match [a-z0-9][a-z0-9-]*;
paths are absolute or `~/`-rooted (no `..`, no trailing `/`); env names
match [A-Za-z_][A-Za-z0-9_]* with scalar values, injected into the
confined command's environment.

Precedence: the BUILT-IN catalog wins on name collision — an entry named
`github` is ignored in favor of the catalog. Multiple `--use-*` flags
(built-in and custom) union; grants are additive-only. Merge order in
the profile: manifest -> services -> folder groups -> env knobs (first
occurrence wins). services.yaml is read only when a run names a
non-built-in `--use-*` id; built-in-only runs never touch it.

Troubleshooting:

- "unknown service" — the error lists the built-ins, the discovered
  services.yaml entries, and this section. Fix the flag name or add the
  entry to services.yaml.
- `services.yaml:<line>: ...` — a schema error; fix the named line.
- "ungrantable" / "blocklisted" — see Safety below; writes to blocklisted
  roots are rejected even from services.yaml; a blocklisted read is
  honored with a loud warning banner.

## Folder groups (--folders)

`~/.cube-sandbox/folders.yaml` holds named groups:

    apiVersion: cube-sandbox/v1
    groups:
      projecta:
        write: [~/work/projecta]
        read: [~/shared/notes]

Group names match [a-z0-9][a-z0-9-]*; `read:`/`write:` lists are
optional; paths are absolute or `~/`-rooted. Select per run (repeatable,
accumulates, unions):

    cube-sandbox launch --folders projecta <profile>

Also on show / sbpl / probe — dry-run the widened grants there first.
The file is never read without the flag. Blocklist per direction: a
`write:` touching `~/.ssh`, `~/.gnupg` or `~/Library/Keychains` is
rejected (exit 2); a `read:` hit is honored with a loud warning banner.

Env knobs: CUBE_SANDBOX_EXTRA_READ / CUBE_SANDBOX_EXTRA_WRITE —
colon-separated grants, `~` ok. A blocklisted EXTRA_WRITE is rejected; a
blocklisted EXTRA_READ is honored, never silent (loud banner).

## Safety

- Never hand-edit a staged cache profile (`harness-<key10>.sb`) or its
  `.src` stamp. They are content-addressed: any config change produces a
  new key and the next launch rebuilds; a hand edit is discarded or
  flagged by the provenance warning.
- Do not edit a manifest, services.yaml or folders.yaml while a confined
  session launched from it is running.
- Run `cube-sandbox clean` between sessions.
- `~/.ssh`, `~/.gnupg` and `~/Library/Keychains` are NEVER grantable —
  from any source (manifest, catalog, services.yaml, folders.yaml, env
  knobs). ssh remotes under confinement fail loudly by design.
- Grants are additive-only: services and folder groups GRANT folders;
  they never forbid commands.
''';
}

/// Ensures [home]/.cube-sandbox/AGENTS.md exists (AC1) — write-if-missing.
/// Returns the differing-file notice text (also printed once to [err],
/// default stderr) or null when nothing was written or the file matches.
/// NEVER throws: a manual that cannot be written must never break a verb
/// (AC2: an identical file is not rewritten; AC3: a user-owned file is
/// preserved, exactly one notice per process).
String? ensureAgentsMd(String home, {void Function(String)? err}) {
  final path = '${expandHome(home)}/AGENTS.md';
  final current = generateAgentsMd();
  String? notice;
  try {
    final file = io.File(path);
    if (!file.existsSync()) {
      io.Directory(expandHome(home)).createSync(recursive: true);
      file.writeAsStringSync(current, flush: true);
      return null;
    }
    if (file.readAsStringSync() != current) {
      notice =
          '$kAgentsMdPath differs from this build\'s generated manual — '
          'left untouched (your file is preserved). Run '
          '`cube-sandbox init --force` to replace it with the current text.';
    }
  } on io.FileSystemException {
    return null; // fail-soft: never break a verb over the manual
  }
  if (notice != null && !_noticed) {
    _noticed = true;
    (err ?? _stderr).call(notice);
  }
  return notice;
}

/// `init [--force]`: ensure the dot-dir, then write-if-missing — or
/// replace when [force] (the only overwrite seam, AC4). Returns the verb
/// exit code (0; failures surface as FileSystemException → exit 2).
int initAgentsMd({
  required String home,
  required bool force,
  void Function(String)? out,
  void Function(String)? err,
}) {
  void say(String s) => out?.call(s);
  final dirPath = expandHome(home);
  io.Directory(dirPath).createSync(recursive: true);
  final file = io.File('$dirPath/AGENTS.md');
  final current = generateAgentsMd();
  final exists = file.existsSync();
  if (!exists) {
    file.writeAsStringSync(current, flush: true);
    say('wrote $kAgentsMdPath');
    return 0;
  }
  if (file.readAsStringSync() == current) {
    say(force ? 'refreshed $kAgentsMdPath' : '$kAgentsMdPath is current');
    return 0;
  }
  if (!force) {
    (err ?? _stderr).call(
      '$kAgentsMdPath exists and differs from this build\'s generated '
      'manual — not overwritten. Run `cube-sandbox init --force` to '
      'replace it (your file is not preserved by --force).',
    );
    return 0;
  }
  file.writeAsStringSync(current, flush: true);
  say('replaced $kAgentsMdPath (--force)');
  return 0;
}

/// `~` -> [home] for the kAgentsMdPath spelling used in notices.
String expandHome(String home) => '$home/.cube-sandbox';

void _stderr(String s) => io.stderr.writeln(s);
